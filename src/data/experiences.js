export const getExperience = (id) => EXPERIENCES.find((e) => e.id === id);

export const getExperiencesByDestination = (destinationId) =>
  EXPERIENCES.filter((e) => e.destinationId === destinationId);

/**
 * Score an experience against the user's selected interests.
 * Primary category match = 3 points, each tag match = 1.
 */
export function scoreExperience(experience, interestIds = []) {
  if (!interestIds.length) return 0;
  let score = 0;
  if (interestIds.includes(experience.category)) score += 3;
  for (const tag of experience.tags ?? []) {
    if (interestIds.includes(tag)) score += 1;
  }
  return score;
}
